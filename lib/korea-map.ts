function smoothPath(pts: [number, number][]): string {
  const n = pts.length;
  const mid = (a: [number, number], b: [number, number]) => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2];
  const m = mid(pts[n - 1], pts[0]);
  let d = `M${m[0]},${m[1]}`;
  for (let i = 0; i < n; i++) {
    const p = pts[i];
    const q = mid(p, pts[(i + 1) % n]);
    d += ` Q${p[0]},${p[1]} ${q[0]},${q[1]}`;
  }
  return d + "Z";
}

